const langMeta = {
  ka: { label: 'GE', htmlLang: 'ka' },
  en: { label: 'EN', htmlLang: 'en' },
  ru: { label: 'RU', htmlLang: 'ru' },
};

let currentLang = localStorage.getItem('lang') || 'ka';

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  const t = i18n[lang];
  const meta = langMeta[lang];

  // html lang attr
  document.documentElement.lang = meta.htmlLang;

  // meta tags
  document.title = t['meta.title'];
  const descEl = document.querySelector('meta[name="description"]');
  if (descEl) descEl.setAttribute('content', t['meta.desc']);

  // all data-i18n elements (innerHTML for ones with html)
  const htmlKeys = ['hero.title'];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      if (htmlKeys.includes(key)) {
        el.innerHTML = t[key];
      } else {
        el.textContent = t[key];
      }
    }
  });

  // Update lang button
  document.getElementById('langFlag').innerHTML = flagSVG[lang];
  document.getElementById('langLabel').textContent = meta.label;

  // Update active option
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

